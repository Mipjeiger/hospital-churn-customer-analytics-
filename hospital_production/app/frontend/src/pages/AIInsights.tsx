import React, { useState, useRef } from "react";
import { useMutation } from "@tanstack/react-query";
import { api, LLMMessage } from "../lib/api";
import { LoadingSpinner } from "../components/ui/States";

type Role = "executive" | "clinical" | "ops" | "risk";

const ROLES: Role[] = ["executive", "clinical", "ops", "risk"];

const ROLE_DESCRIPTIONS: Record<Role, string> = {
  executive: "Strategic overview, financial performance, and board-level metrics.",
  clinical: "Clinical outcomes, patient safety, and evidence-based recommendations.",
  ops: "Operational efficiency, bed management, and resource allocation.",
  risk: "Risk identification, compliance, and mitigation strategies.",
};

interface ChatMessage {
  role: "user" | "assistant";
  content: string;
  provider?: string;
}

const AIInsights: React.FC = () => {
  const [role, setRole] = useState<Role>("executive");
  const [question, setQuestion] = useState("");
  const [history, setHistory] = useState<ChatMessage[]>([]);
  const chatRef = useRef<HTMLDivElement>(null);

  const agentMutation = useMutation({
    mutationFn: (q: string) =>
      api.llmAgent({
        question: q,
        role,
        history: history.map((m) => ({ role: m.role, content: m.content })),
      }),
    onSuccess: (data) => {
      setHistory((prev) => [
        ...prev,
        { role: "assistant", content: data.answer },
      ]);
      setTimeout(() => {
        chatRef.current?.scrollTo({
          top: chatRef.current.scrollHeight,
          behavior: "smooth",
        });
      }, 50);
    },
  });

  const handleSend = (e: React.FormEvent) => {
    e.preventDefault();
    const q = question.trim();
    if (!q) return;
    setHistory((prev) => [...prev, { role: "user", content: q }]);
    setQuestion("");
    agentMutation.mutate(q);
  };

  return (
    <div className="page">
      <div className="page-header">
        <h2 className="page-title">AI Management Insights</h2>
      </div>
      <p className="page-desc">
        Role-based AI assistant powered by <code>POST /llm/agent</code>.
        Responses are generated by the configured LLM provider (Groq / NineRouter
        / HuggingFace).
      </p>

      {/* Role selector */}
      <div className="role-selector">
        {ROLES.map((r) => (
          <button
            key={r}
            className={`role-btn${role === r ? " role-btn--active" : ""}`}
            onClick={() => setRole(r)}
          >
            {r.charAt(0).toUpperCase() + r.slice(1)}
          </button>
        ))}
      </div>
      <p className="role-desc">{ROLE_DESCRIPTIONS[role]}</p>

      {/* Chat history */}
      <div className="chat-window" ref={chatRef}>
        {history.length === 0 && (
          <div className="chat-empty">
            <p>Ask a question in your role as <strong>{role}</strong>.</p>
            <p className="text-sm muted">
              Example: "What is our current churn risk level?" or "Summarise staff attendance."
            </p>
          </div>
        )}
        {history.map((msg, i) => (
          <div
            key={i}
            className={`chat-bubble chat-bubble--${msg.role}`}
          >
            <span className="chat-role">
              {msg.role === "user" ? "You" : "AI"}
            </span>
            <p className="chat-text">{msg.content}</p>
          </div>
        ))}
        {agentMutation.isPending && (
          <div className="chat-bubble chat-bubble--assistant">
            <span className="chat-role">AI</span>
            <LoadingSpinner label="Generating response…" />
          </div>
        )}
        {agentMutation.isError && (
          <div className="error-inline">
            ⚠️ {(agentMutation.error as Error).message}
          </div>
        )}
      </div>

      {/* Input */}
      <form onSubmit={handleSend} className="chat-input-row">
        <input
          className="form-input"
          type="text"
          placeholder={`Ask as ${role}…`}
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          disabled={agentMutation.isPending}
        />
        <button
          className="btn btn-primary"
          type="submit"
          disabled={agentMutation.isPending || !question.trim()}
        >
          Send
        </button>
        <button
          type="button"
          className="btn"
          onClick={() => {
            setHistory([]);
            agentMutation.reset();
          }}
        >
          Clear
        </button>
      </form>
    </div>
  );
};

export default AIInsights;

